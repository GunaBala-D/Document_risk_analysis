"""Exploratory data analysis of the processed (extracted) dataset.

Writes docs/EDA.md and charts under docs/images/. Every number in the report is computed
here from data/processed/dataset_<feature_version>.parquet - nothing is typed in by hand.

Usage:
    python -m training.eda
"""

from __future__ import annotations

import json

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

from src.config import DATA_DIR, PROJECT_ROOT  # noqa: E402
from src.features.builder import load_registry  # noqa: E402
from src.models.evaluation import CLASSES  # noqa: E402

INK, MUTED, GRID, SURFACE, SERIES = "#0b0b0b", "#898781", "#e1e0d9", "#fcfcfb", "#2a78d6"
OUT = PROJECT_ROOT / "docs" / "images"


def _style(ax) -> None:
    ax.set_facecolor(SURFACE)
    for side in ("top", "right", "left"):
        ax.spines[side].set_visible(False)
    ax.spines["bottom"].set_color("#c3c2b7")
    ax.tick_params(colors=MUTED, labelsize=9)
    ax.grid(axis="x", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)


def _hbar(series: pd.Series, title: str, path, fmt="{:,.0f}") -> None:
    fig, ax = plt.subplots(figsize=(7, 0.38 * len(series) + 1.2), facecolor=SURFACE)
    _style(ax)
    ax.barh(series.index[::-1], series.values[::-1], color=SERIES, height=0.6)
    for y, v in enumerate(series.values[::-1]):
        ax.text(v, y, " " + fmt.format(v), va="center", fontsize=9, color=INK)
    ax.set_title(title, loc="left", fontsize=11, color=INK)
    fig.tight_layout()
    fig.savefig(path, dpi=130)
    plt.close(fig)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    ds = pd.read_parquet(DATA_DIR / "processed" / f"dataset_{load_registry().version}.parquet")
    reg = load_registry()
    feats = reg.names

    label_counts = ds["risk_label"].value_counts().reindex(CLASSES)
    _hbar(label_counts, f"Contracts by risk label (synthetic, n={len(ds):,})", OUT / "label_distribution.png")

    reasons = ds["label_reasons"].fillna("").str.split("|").explode()
    reasons = reasons[reasons != ""].value_counts()
    _hbar(reasons, "Labeling-policy factors: how often each fired", OUT / "label_factors.png")

    missing = ds[feats].isna().mean().sort_values(ascending=False)
    missing = missing[missing > 0]
    by_class = ds.groupby("risk_label")[feats].median().reindex(CLASSES).T.round(2)
    spearman = ds[feats].corrwith(ds["risk_points"], method="spearman").sort_values(key=abs, ascending=False)
    method_by_label = pd.crosstab(ds["extraction_method"], ds["risk_label"]).reindex(columns=CLASSES)
    extraction = json.loads((DATA_DIR / "processed" / "extraction_eval.json").read_text(encoding="utf-8"))
    doc_type = json.loads((DATA_DIR / "processed" / "doc_type_eval.json").read_text(encoding="utf-8"))
    meta = json.loads((DATA_DIR / "processed" / "dataset_meta.json").read_text(encoding="utf-8"))

    def md(df: pd.DataFrame | pd.Series) -> str:
        return df.to_markdown() if hasattr(df, "to_markdown") else str(df)

    ext_rows = pd.DataFrame({
        f: {m: v["accuracy"] for m, v in by_m.items()} for f, by_m in extraction.items() if f != "_meta"
    }).T[["all", "native", "docx", "ocr"]]

    lines = [
        "# Exploratory Data Analysis",
        "",
        "> **All data is synthetic** (generated by `scripts/generate_dataset.py`). Numbers below describe the",
        "> synthetic corpus only and say nothing about real enterprise contracts.",
        "",
        f"Dataset version `{meta['dataset_version']}`, feature version `{meta['feature_version']}`, "
        f"{len(ds):,} contracts, {ds['vendor_key'].nunique()} distinct vendors (as extracted), "
        f"submission dates {ds['submission_date'].min()} to {ds['submission_date'].max()}.",
        "",
        "## 1. Label distribution",
        "",
        "![labels](images/label_distribution.png)",
        "",
        md((label_counts / len(ds)).round(3).rename("share").to_frame().assign(count=label_counts)),
        "",
        "CRITICAL is the minority class (the imbalance the modelling phase must handle).",
        "",
        "## 2. Labeling-policy factors",
        "",
        "![factors](images/label_factors.png)",
        "",
        "## 3. Extraction quality vs ground truth (accuracy by extraction method)",
        "",
        md(ext_rows.round(3)),
        "",
        f"Document-type detection accuracy on {doc_type['n']} documents (contracts + invoices + POs): "
        f"**{doc_type['accuracy']:.3f}**.",
        "",
        "Caveat: the synthetic contracts use a finite set of templates, so extraction is far easier than on",
        "real contracts. OCR documents show the expected small drop (character errors in names).",
        "",
        "## 4. Extraction method by risk label",
        "",
        md(method_by_label),
        "",
        "## 5. Missing feature values",
        "",
        md(missing.round(3).rename("missing_share").to_frame()),
        "",
        "Missingness is structural, not random: vendor-history features are NaN for a vendor's first",
        "contract, `termination_notice_days` is NaN when no termination clause exists.",
        "",
        "## 6. Feature medians by risk label",
        "",
        md(by_class),
        "",
        "## 7. Spearman correlation of each feature with policy risk points",
        "",
        md(spearman.round(3).rename("spearman_rho").to_frame()),
        "",
    ]
    (PROJECT_ROOT / "docs" / "EDA.md").write_text("\n".join(lines), encoding="utf-8")
    print("Wrote docs/EDA.md and", sorted(p.name for p in OUT.glob("*.png")))


if __name__ == "__main__":
    main()
